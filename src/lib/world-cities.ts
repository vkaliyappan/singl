export const WORLD_CITIES: WorldCity[] = RAW.map(([name, country, zone]) => ({ name, country, zone }))

const fold = (s: string) =>
  s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase()

const INDEX = WORLD_CITIES.map((c) => ({ city: c, name: fold(c.name), country: fold(c.country) }))

/** Cities whose name (or country) matches `query`, name-prefix matches first. */
export function searchCities(query: string, limit = 20): WorldCity[] {
  const q = fold(query.trim())
  if (!q) return []
  const prefix: WorldCity[] = []
  const inner: WorldCity[] = []
  const byCountry: WorldCity[] = []
  for (const { city, name, country } of INDEX) {
    if (name.startsWith(q)) prefix.push(city)
    else if (name.includes(q)) inner.push(city)
    else if (country.startsWith(q)) byCountry.push(city)
  }
  return [...prefix, ...inner, ...byCountry].slice(0, limit)
}
