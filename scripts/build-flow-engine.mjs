// Bundles the flow runner (src/lib/twx-flow/engine/entry.ts and the evaluator
// modules it imports) into one script for the Rust engine, which embeds it with
// include_str! and runs it in QuickJS. Re-run after changing anything under
// src/lib/twx-flow that the runner uses:  pnpm flow:engine
import { build } from "esbuild"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const outfile = path.join(root, "src-tauri/crates/singl-core/src/flow/engine.js")

await build({
  entryPoints: [path.join(root, "src/lib/twx-flow/engine/entry.ts")],
  outfile,
  bundle: true,
  format: "iife",
  platform: "neutral",
  target: "es2022",
  alias: { "@": path.join(root, "src") },
  banner: { js: "// Generated by scripts/build-flow-engine.mjs: do not edit." },
  legalComments: "none",
  logLevel: "info",
})
